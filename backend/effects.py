def video_fps(path) -> float:
    try:
        import cv2
        cap = cv2.VideoCapture(str(path))
        fps = cap.get(cv2.CAP_PROP_FPS) or 30
        cap.release()
        return float(min(60, max(15, fps)))
    except Exception:
        return 30.0


def video_filters(inp: str, filt: str, events: list, dur: float, fps: float, emoji_inputs: dict,
                  size=(1080, 1920), graded=False) -> tuple:
    """Filter-graph pieces that take [inp] (the 1080x1920 picture) to a new label. emoji_inputs maps
    event index -> ffmpeg input index of that event's emoji image stream. graded=True means the colour grading
    was already applied before scaling (see split_look), so only the size-dependent part is added here.
    Returns (pieces, out_label)."""
    chain = []
    pre, post = split_look(filt)
    look = post if graded else ",".join(p for p in (pre, post) if p)
    if look:
        chain.append(look)

    zoom_terms, shake = [], []
    flashes, blurs = [], []
    ending = next((e for e in events if e["fx"] == "ending"), None)
    for e in events:
        t = e["t"]
        if e["fx"] == "punch":
            zoom_terms.append(f"0.16*between(it,{t:.3f},{t + 0.9:.3f})*"
                              f"if(lt(it-{t:.3f},0.07),(it-{t:.3f})/0.07,exp(-(it-{t:.3f}-0.07)*6))")
        elif e["fx"] == "shake":
            zoom_terms.append(f"0.07*between(it,{t:.3f},{t + 0.6:.3f})")
            shake.append((t, 0.6))
        elif e["fx"] == "flash":
            flashes.append(t)
            zoom_terms.append(f"0.1*between(it,{t:.3f},{t + 0.6:.3f})*exp(-(it-{t:.3f})*5)")
        elif e["fx"] == "blur":
            blurs.append(t)
    if ending:
        e0 = ending["t"]
        span = max(0.3, dur - e0)
        zoom_terms.append(f"0.14*between(it,{e0:.3f},{dur + 1:.3f})*min(1,(it-{e0:.3f})/{span:.3f})")

    if zoom_terms or shake:
        z = "1+" + "+".join(zoom_terms) if zoom_terms else "1"
        sx = "+".join(f"26*sin(it*83)*between(it,{t:.3f},{t + d:.3f})*(1-(it-{t:.3f})/{d})" for t, d in shake) or "0"
        sy = "+".join(f"20*cos(it*71)*between(it,{t:.3f},{t + d:.3f})*(1-(it-{t:.3f})/{d})" for t, d in shake) or "0"
        chain.append(f"zoompan=z='{z}':x='iw/2-iw/zoom/2+{sx}':y='ih/2-ih/zoom/2+{sy}'"
                     f":d=1:s={size[0]}x{size[1]}:fps={fps:g}")
    if blurs:
        when = "+".join(f"between(t,{t:.3f},{t + 0.22:.3f})" for t in blurs)
        chain.append(f"avgblur=sizeX=3:sizeY=70:enable='{when}'")
    if flashes:
        b = "+".join(f"0.85*between(t,{t:.3f},{t + 0.3:.3f})*(1-(t-{t:.3f})/0.3)" for t in flashes)
        chain.append(f"eq=brightness='min(1,{b})':eval=frame")
    if ending:
        chain += [f"{p}:enable='gte(t,{ending['t']:.3f})'" for p in ENDING_GRADE]

    pieces, label = [], inp
    if chain:
        pieces.append(f"[{inp}]{','.join(chain)}[fx0]")
        label = "fx0"
    side = 0
    for i, e in enumerate(events):
        if i not in emoji_inputs:
            continue
        t = e["t"]
        show = (dur - t + 0.1) if e["fx"] == "ending" else 1.4
        if e["fx"] == "ending":
            x, y = "(W-w)/2", "H*0.6"
        else:
            x = ["(W-w)/2+220", "(W-w)/2-220"][side % 2]
            y = "H*0.55"
            side += 1
        k = emoji_inputs[i]
        scale = f"scale=-1:{int(min(300, size[1] * 0.4))}," if size[1] < 1000 else ""
        pieces.append(f"[{k}:v]{scale}format=rgba,setpts=PTS+{t:.3f}/TB,fade=in:st={t:.3f}:d=0.15:alpha=1,"
                      f"fade=out:st={t + show - 0.2:.3f}:d=0.2:alpha=1[em{i}]")
        pieces.append(f"[{label}][em{i}]overlay=x='{x}':y='{y}+12*sin((t-{t:.3f})*5)':eof_action=pass"
                      f":enable='between(t,{t:.3f},{t + show:.3f})'[fx{i + 1}e]")
        label = f"fx{i + 1}e"
    return pieces, label
