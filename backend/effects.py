# ================================================================ sound effects (synthesised)
SR = 48000


def _t(sec):
    return np.arange(int(SR * sec)) / SR


def _sweep(f0, f1, sec, curve=6.0):
    """Sine whose pitch glides from f0 to f1 (exponential-ish)."""
    t = _t(sec)
    f = f1 + (f0 - f1) * np.exp(-t * curve)
    return np.sin(2 * np.pi * np.cumsum(f) / SR)


def _lowpass_sweep(x, cutoffs):
    """One-pole low-pass whose cutoff (Hz) changes per sample."""
    a = 1 - np.exp(-2 * np.pi * np.asarray(cutoffs) / SR)
    y = np.empty_like(x)
    acc = 0.0
    for i in range(len(x)):
        acc += a[i] * (x[i] - acc)
        y[i] = acc
    return y


def _synth(name):
    rng = np.random.default_rng(7)
    if name == "boom":                         # deep cinematic boom
        t = _t(1.6)
        body = _sweep(120, 42, 1.6, 7) + 0.35 * _sweep(240, 84, 1.6, 7)
        env = np.minimum(t / 0.004, 1) * np.exp(-t * 2.6)
        click = rng.standard_normal(len(t)) * np.exp(-t * 90) * 0.5
        return np.tanh(2.6 * (body * env + _lowpass_sweep(click, np.full(len(t), 900.0))))
    if name == "hit":                          # short punchy impact
        t = _t(0.45)
        body = _sweep(180, 55, 0.45, 30) * np.exp(-t * 11)
        noise = _lowpass_sweep(rng.standard_normal(len(t)), np.full(len(t), 3500.0)) * np.exp(-t * 45)
        return np.tanh(2.2 * (body + 1.4 * noise))
    if name == "whoosh":
        t = _t(0.7)
        p = t / t[-1]
        cut = 300 + 6500 * np.sin(np.pi * p) ** 2
        env = np.sin(np.pi * p ** 0.7) ** 2
        return _lowpass_sweep(rng.standard_normal(len(t)), cut) * env * 3.2
    if name == "riser":                        # builds up and stops at the event time
        t = _t(1.6)
        p = t / t[-1]
        noise = _lowpass_sweep(rng.standard_normal(len(t)), 200 + 9000 * p ** 2) * 2.2
        tone = np.sin(2 * np.pi * np.cumsum(200 + 1000 * p ** 2) / SR) * 0.35
        return (noise + tone) * p ** 2.2
    if name == "ding":
        t = _t(1.3)
        x = sum(a * np.sin(2 * np.pi * f * t) for f, a in ((1318.5, 1), (2637, 0.4), (3955, 0.18), (2093, 0.12)))
        return x * np.minimum(t / 0.003, 1) * np.exp(-t * 4)
    if name == "glitch":
        out = []
        for i in range(14):
            n = int(SR * 0.028)
            if i % 4 == 3:
                out.append(np.zeros(n))
                continue
            f = rng.uniform(90, 1400)
            sq = np.sign(np.sin(2 * np.pi * f * np.arange(n) / SR))
            out.append(np.round(sq * rng.uniform(0.4, 1) * 4) / 4)
        return np.concatenate(out) * 0.6
    if name == "shutter":                      # camera click
        t = _t(0.25)
        x = rng.standard_normal(len(t))
        x = x - _lowpass_sweep(x, np.full(len(t), 1500.0))
        env = np.exp(-t * 160) + 0.7 * np.exp(-np.clip(t - 0.08, 0, None) * 160) * (t >= 0.08)
        return x * env
    if name == "bassdrop":
        t = _t(1.8)
        return np.tanh(3 * _sweep(140, 32, 1.8, 2.2) * np.minimum(t / 0.01, 1) * np.exp(-t * 1.3))
    if name == "pop":
        t = _t(0.14)
        return np.sin(2 * np.pi * np.cumsum(400 + 900 * t / t[-1]) / SR) * np.exp(-t * 32)
    raise KeyError(name)


BUILTIN_SOUNDS = {   # id -> (label, lead): lead = seconds before the event time the sound starts
    "boom": ("Boom", 0.0), "hit": ("Hit", 0.0), "whoosh": ("Whoosh", 0.3), "riser": ("Riser (builds up)", 1.6),
    "bassdrop": ("Bass drop", 0.0), "ding": ("Ding", 0.0), "glitch": ("Glitch", 0.0),
    "shutter": ("Camera shutter", 0.0), "pop": ("Pop", 0.0),
}


def _builtin_path(name) -> Path:
    path = SFX_BUILTIN / f"{name}.wav"
    if not path.exists():
        x = _synth(name).astype(np.float64)
        x = x / (np.abs(x).max() or 1) * 0.9
        with wave.open(str(path), "wb") as w:
            w.setnchannels(1)
            w.setsampwidth(2)
            w.setframerate(SR)
            w.writeframes((x * 32767).astype(np.int16).tobytes())
    return path


def sounds() -> list:
    out = [{"id": f"builtin/{k}", "name": v[0], "source": "builtin"} for k, v in BUILTIN_SOUNDS.items()]
    for p in sorted(SFX_MINE.iterdir(), key=lambda p: p.name.lower()):
        if p.suffix.lower() in AUDIO_EXT:
            out.append({"id": f"mine/{p.name}", "name": p.stem, "source": "mine"})
    return out


def resolve_sound(sound_id: str):
    """(path, lead seconds) for a sound id, or (None, 0)."""
    if not sound_id or "/" not in sound_id:
        return None, 0.0
    kind, name = sound_id.split("/", 1)
    if kind == "builtin" and name in BUILTIN_SOUNDS:
        return _builtin_path(name), BUILTIN_SOUNDS[name][1]
    if kind == "mine":
        p = (SFX_MINE / name).resolve()
        if p.parent == SFX_MINE.resolve() and p.exists() and p.suffix.lower() in AUDIO_EXT:
            return p, 0.0
    return None, 0.0


# ================================================================ emoji images
def emoji_png(emoji: str, size=300) -> Path:
    key = "-".join(f"{ord(c):x}" for c in emoji)
    path = EMOJI_DIR / f"{key}_{size}.png"
    if path.exists():
        return path
    from PIL import Image, ImageDraw, ImageFont
    font = ImageFont.truetype(_emoji_font(), int(size * 0.72))
    im = Image.new("RGBA", (size * 2, size * 2), (0, 0, 0, 0))
    ImageDraw.Draw(im).text((size // 2, size // 2), emoji, font=font, embedded_color=True)
    box = im.getbbox()
    if box:
        im = im.crop(box)
    im.thumbnail((size, size))
    im.save(path)
    return path


def _emoji_font() -> str:
    for p in (r"C:\Windows\Fonts\seguiemj.ttf", "/System/Library/Fonts/Apple Color Emoji.ttc",
              "/usr/share/fonts/truetype/noto/NotoColorEmoji.ttf"):
        if Path(p).exists():
            return p
    raise RuntimeError("No colour emoji font found on this PC")


# ================================================================ suggestions
def _peaks(z, start, end, spacing=3.0, floor=1.4):
    """Loudest seconds inside the clip, as (seconds from clip start, z), loudest first, spaced apart."""
    a, b = max(0, int(start)), min(len(z), int(math.ceil(end)))
    seg = np.asarray(z[a:b], dtype=float)
    if len(seg) < 3:
        return []
    floor = min(floor, max(0.5, float(np.percentile(seg, 85))))   # quieter clips still get their loudest beats
    cand = [(i, v) for i, v in enumerate(seg)
            if v >= floor and v >= seg[max(0, i - 1)] and v >= seg[min(len(seg) - 1, i + 1)]]
    cand.sort(key=lambda c: -c[1])
    out = []
    for i, v in cand:
        t = a + i - start
        if 0.6 < t < end - start - 0.4 and all(abs(t - o) >= spacing for o, _ in out):
            out.append((t, float(v)))
    return out


def _snap_to_word(t, words, start):
    best = None
    for w in words:
        ws = w["start"] - start
        if abs(ws - t) <= 0.7 and (best is None or abs(ws - t) < abs(best - t)):
            best = ws
    return best if best is not None else t


def suggest(preset: str, clip: dict, z, words: list, offset: float) -> dict:
    """Effects for one clip. `words` are timed against the clip's source file; `offset` is where the cut starts
    inside that file (so a word at offset is t=0)."""
    preset = preset if preset in PRESETS else "edit"
    dur = float(clip["end"] - clip["start"])
    result = {"effects_preset": preset, "filter": PRESET_FILTER[preset], "effects": []}
    if preset == "none" or dur <= 2:
        return result
    rel_words = [{"start": w["start"] - offset, "text": w["text"]} for w in words
                 if 0 <= w["start"] - offset < dur]
    peaks = _peaks(z if z is not None else [], clip["start"], clip["end"],
                   spacing={"subtle": 6, "cinematic": 6}.get(preset, 3.5))
    peaks = [(round(_snap_to_word(t, rel_words, 0.0), 2), v) for t, v in peaks]   # land on the word's onset
    ev = []
    add = lambda t, fx, sound="", emoji="": ev.append(
        {"t": round(max(0.0, min(dur - 0.1, t)), 2), "fx": fx, "sound": sound, "emoji": emoji})
    mood_emoji = MOOD_EMOJI.get(clip.get("mood"), "💀")
    ending_at = max(dur * 0.6, dur - 1.8)

    if preset == "subtle":
        add(0, "punch", "builtin/whoosh")
        for t, _ in peaks[:2]:
            add(t, "punch")
    elif preset == "edit":
        add(0, "punch", "builtin/whoosh")
        usable = [p for p in peaks if p[0] < ending_at - 1.0][: max(1, int(dur / 5))]
        for n, (t, v) in enumerate(sorted(usable)):
            biggest = v == max(p[1] for p in usable)
            add(t, "flash" if biggest else "punch", "builtin/boom" if biggest else "builtin/hit")
        if dur > 8:
            add(ending_at - 0.25, "blur", "builtin/whoosh")
        add(ending_at, "ending", "builtin/boom", "💀" if clip.get("mood") in (None, "hype", "tense") else mood_emoji)
    elif preset == "hype":
        add(0, "shake", "builtin/boom")
        usable = [p for p in peaks if 0.8 < p[0] < ending_at - 1.0][: max(2, int(dur / 4))]
        for n, (t, v) in enumerate(sorted(usable)):
            add(t, ["shake", "punch", "flash"][n % 3], ["builtin/boom", "builtin/hit", "builtin/glitch"][n % 3])
        laughs = [w["start"] for w in rel_words if LAUGH.search(w["text"])]
        if laughs:
            add(laughs[0], "emoji", "builtin/pop", "😂")
        shocks = [w["start"] for w in rel_words if SHOCK.search(w["text"]) and w["start"] > 1.5]
        if shocks and not laughs:
            add(shocks[0], "emoji", "builtin/pop", random.Random(clip.get("id")).choice(["😳", "🤯", "😱"]))
        add(ending_at, "ending", "builtin/bassdrop", mood_emoji)
    elif preset == "cinematic":
        if peaks:
            t, _ = max(peaks, key=lambda p: p[1])
            add(t, "flash", "builtin/riser")
            add(t + 0.02, "punch", "builtin/bassdrop")
        add(0, "none", "builtin/whoosh")
    ev.sort(key=lambda e: e["t"])
    result["effects"] = ev
    return result


def clean(events, dur: float) -> list:
    """Validates effects coming from the app."""
    out = []
    for e in events or []:
        if not isinstance(e, dict):
            continue
        try:
            t = float(e.get("t", 0))
        except (TypeError, ValueError):
            continue
        fx = e.get("fx") if e.get("fx") in VISUALS else "none"
        sound = str(e.get("sound") or "")
        emoji = str(e.get("emoji") or "")[:8]
        if fx == "none" and not sound:
            continue
        out.append({"t": round(max(0.0, min(t, max(0.0, dur - 0.05))), 2), "fx": fx, "sound": sound, "emoji": emoji})
    out.sort(key=lambda e: e["t"])
    return out[:60]


# ================================================================ ffmpeg
def video_fps(path) -> float:
    try:
        import cv2
        cap = cv2.VideoCapture(str(path))
        fps = cap.get(cv2.CAP_PROP_FPS) or 30
        cap.release()
        return float(min(60, max(15, fps)))
    except Exception:
        return 30.0


def video_filters(inp: str, filt: str, events: list, dur: float, fps: float, emoji_inputs: dict,
                  size=(1080, 1920)) -> tuple:
    """Filter-graph pieces that take [inp] (the 1080x1920 picture) to a new label. emoji_inputs maps
    event index -> ffmpeg input index of that event's emoji image stream. Returns (pieces, out_label)."""
    chain = []
    if FILTERS.get(filt, ("", ""))[1]:
        chain.append(FILTERS[filt][1])

    zoom_terms, shake = [], []
    flashes, blurs = [], []
    ending = next((e for e in events if e["fx"] == "ending"), None)
    for e in events:
        t = e["t"]
        if e["fx"] == "punch":
            zoom_terms.append(f"0.16*between(it,{t:.3f},{t + 0.9:.3f})*"
                              f"if(lt(it-{t:.3f},0.07),(it-{t:.3f})/0.07,exp(-(it-{t:.3f}-0.07)*6))")
        elif e["fx"] == "shake":
            zoom_terms.append(f"0.07*between(it,{t:.3f},{t + 0.6:.3f})")
            shake.append((t, 0.6))
        elif e["fx"] == "flash":
            flashes.append(t)
            zoom_terms.append(f"0.1*between(it,{t:.3f},{t + 0.6:.3f})*exp(-(it-{t:.3f})*5)")
        elif e["fx"] == "blur":
            blurs.append(t)
    if ending:
        e0 = ending["t"]
        span = max(0.3, dur - e0)
        zoom_terms.append(f"0.14*between(it,{e0:.3f},{dur + 1:.3f})*min(1,(it-{e0:.3f})/{span:.3f})")

    if zoom_terms or shake:
        z = "1+" + "+".join(zoom_terms) if zoom_terms else "1"
        sx = "+".join(f"26*sin(it*83)*between(it,{t:.3f},{t + d:.3f})*(1-(it-{t:.3f})/{d})" for t, d in shake) or "0"
        sy = "+".join(f"20*cos(it*71)*between(it,{t:.3f},{t + d:.3f})*(1-(it-{t:.3f})/{d})" for t, d in shake) or "0"
        chain.append(f"zoompan=z='{z}':x='iw/2-iw/zoom/2+{sx}':y='ih/2-ih/zoom/2+{sy}'"
                     f":d=1:s={size[0]}x{size[1]}:fps={fps:g}")
    if blurs:
        when = "+".join(f"between(t,{t:.3f},{t + 0.22:.3f})" for t in blurs)
        chain.append(f"avgblur=sizeX=3:sizeY=70:enable='{when}'")
    if flashes:
        b = "+".join(f"0.85*between(t,{t:.3f},{t + 0.3:.3f})*(1-(t-{t:.3f})/0.3)" for t in flashes)
        chain.append(f"eq=brightness='min(1,{b})':eval=frame")
    if ending:
        chain += [f"{p}:enable='gte(t,{ending['t']:.3f})'" for p in ENDING_GRADE.split(",")]

    pieces, label = [], inp
    if chain:
        pieces.append(f"[{inp}]{','.join(chain)}[fx0]")
        label = "fx0"
    side = 0
    for i, e in enumerate(events):
        if i not in emoji_inputs:
            continue
        t = e["t"]
        show = (dur - t + 0.1) if e["fx"] == "ending" else 1.4
        if e["fx"] == "ending":
            x, y = "(W-w)/2", "H*0.6"
        else:
            x = ["(W-w)/2+220", "(W-w)/2-220"][side % 2]
            y = "H*0.55"
            side += 1
        k = emoji_inputs[i]
        scale = f"scale=-1:{int(min(300, size[1] * 0.4))}," if size[1] < 1000 else ""
        pieces.append(f"[{k}:v]{scale}format=rgba,setpts=PTS+{t:.3f}/TB,fade=in:st={t:.3f}:d=0.15:alpha=1,"
                      f"fade=out:st={t + show - 0.2:.3f}:d=0.2:alpha=1[em{i}]")
        pieces.append(f"[{label}][em{i}]overlay=x='{x}':y='{y}+12*sin((t-{t:.3f})*5)':eof_action=pass"
                      f":enable='between(t,{t:.3f},{t + show:.3f})'[fx{i + 1}e]")
        label = f"fx{i + 1}e"
    return pieces, label
