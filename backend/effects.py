# ================================================================ sound effects (synthesised)
SR = 48000


def _t(sec):
    return np.arange(int(SR * sec)) / SR


def _sweep(f0, f1, sec, curve=6.0):
    """Sine whose pitch glides from f0 to f1 (exponential-ish)."""
    t = _t(sec)
    f = f1 + (f0 - f1) * np.exp(-t * curve)
    return np.sin(2 * np.pi * np.cumsum(f) / SR)


def _lowpass_sweep(x, cutoffs):
    """One-pole low-pass whose cutoff (Hz) changes per sample."""
    a = 1 - np.exp(-2 * np.pi * np.asarray(cutoffs) / SR)
    y = np.empty_like(x)
    acc = 0.0
    for i in range(len(x)):
        acc += a[i] * (x[i] - acc)
        y[i] = acc
    return y


def _synth(name):
    rng = np.random.default_rng(7)
    if name == "boom":                         # deep cinematic boom
        t = _t(1.6)
        body = _sweep(120, 42, 1.6, 7) + 0.35 * _sweep(240, 84, 1.6, 7)
        env = np.minimum(t / 0.004, 1) * np.exp(-t * 2.6)
        click = rng.standard_normal(len(t)) * np.exp(-t * 90) * 0.5
        return np.tanh(2.6 * (body * env + _lowpass_sweep(click, np.full(len(t), 900.0))))
    if name == "hit":                          # short punchy impact
        t = _t(0.45)
        body = _sweep(180, 55, 0.45, 30) * np.exp(-t * 11)
        noise = _lowpass_sweep(rng.standard_normal(len(t)), np.full(len(t), 3500.0)) * np.exp(-t * 45)
        return np.tanh(2.2 * (body + 1.4 * noise))
    if name == "whoosh":
        t = _t(0.7)
        p = t / t[-1]
        cut = 300 + 6500 * np.sin(np.pi * p) ** 2
        env = np.sin(np.pi * p ** 0.7) ** 2
        return _lowpass_sweep(rng.standard_normal(len(t)), cut) * env * 3.2
    if name == "riser":                        # builds up and stops at the event time
        t = _t(1.6)
        p = t / t[-1]
        noise = _lowpass_sweep(rng.standard_normal(len(t)), 200 + 9000 * p ** 2) * 2.2
        tone = np.sin(2 * np.pi * np.cumsum(200 + 1000 * p ** 2) / SR) * 0.35
        return (noise + tone) * p ** 2.2
    if name == "ding":
        t = _t(1.3)
        x = sum(a * np.sin(2 * np.pi * f * t) for f, a in ((1318.5, 1), (2637, 0.4), (3955, 0.18), (2093, 0.12)))
        return x * np.minimum(t / 0.003, 1) * np.exp(-t * 4)
    if name == "glitch":
        out = []
        for i in range(14):
            n = int(SR * 0.028)
            if i % 4 == 3:
                out.append(np.zeros(n))
                continue
            f = rng.uniform(90, 1400)
            sq = np.sign(np.sin(2 * np.pi * f * np.arange(n) / SR))
            out.append(np.round(sq * rng.uniform(0.4, 1) * 4) / 4)
        return np.concatenate(out) * 0.6
    if name == "shutter":                      # camera click
        t = _t(0.25)
        x = rng.standard_normal(len(t))
        x = x - _lowpass_sweep(x, np.full(len(t), 1500.0))
        env = np.exp(-t * 160) + 0.7 * np.exp(-np.clip(t - 0.08, 0, None) * 160) * (t >= 0.08)
        return x * env
    if name == "bassdrop":
        t = _t(1.8)
        return np.tanh(3 * _sweep(140, 32, 1.8, 2.2) * np.minimum(t / 0.01, 1) * np.exp(-t * 1.3))
    if name == "pop":
        t = _t(0.14)
        return np.sin(2 * np.pi * np.cumsum(400 + 900 * t / t[-1]) / SR) * np.exp(-t * 32)
    raise KeyError(name)


BUILTIN_SOUNDS = {   # id -> (label, lead): lead = seconds before the event time the sound starts
    "boom": ("Boom", 0.0), "hit": ("Hit", 0.0), "whoosh": ("Whoosh", 0.3), "riser": ("Riser (builds up)", 1.6),
    "bassdrop": ("Bass drop", 0.0), "ding": ("Ding", 0.0), "glitch": ("Glitch", 0.0),
    "shutter": ("Camera shutter", 0.0), "pop": ("Pop", 0.0),
}


def _builtin_path(name) -> Path:
    path = SFX_BUILTIN / f"{name}.wav"
    if not path.exists():
        x = _synth(name).astype(np.float64)
        x = x / (np.abs(x).max() or 1) * 0.9
        with wave.open(str(path), "wb") as w:
            w.setnchannels(1)
            w.setsampwidth(2)
            w.setframerate(SR)
            w.writeframes((x * 32767).astype(np.int16).tobytes())
    return path


def sounds() -> list:
    out = [{"id": f"builtin/{k}", "name": v[0], "source": "builtin"} for k, v in BUILTIN_SOUNDS.items()]
    for p in sorted(SFX_MINE.iterdir(), key=lambda p: p.name.lower()):
        if p.suffix.lower() in AUDIO_EXT:
            out.append({"id": f"mine/{p.name}", "name": p.stem, "source": "mine"})
    return out


def resolve_sound(sound_id: str):
    """(path, lead seconds) for a sound id, or (None, 0)."""
    if not sound_id or "/" not in sound_id:
        return None, 0.0
    kind, name = sound_id.split("/", 1)
    if kind == "builtin" and name in BUILTIN_SOUNDS:
        return _builtin_path(name), BUILTIN_SOUNDS[name][1]
    if kind == "mine":
        p = (SFX_MINE / name).resolve()
        if p.parent == SFX_MINE.resolve() and p.exists() and p.suffix.lower() in AUDIO_EXT:
            return p, 0.0
    return None, 0.0


